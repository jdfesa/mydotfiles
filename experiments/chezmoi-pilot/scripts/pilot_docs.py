def traceability_markdown(
    evidence: dict[str, Any], repo_root: Path, pilot_root: Path, change_root: Path
) -> str:
    validate_traceability(repo_root, pilot_root, change_root, evidence)
    declaration = load_json(pilot_root / "traceability.json")
    rows: list[tuple[str, str, str, str]] = []
    for entry in declaration["entries"]:
        coverage = entry["coverage"]
        kind = coverage["kind"]
        if kind == "automated-check":
            reference = f"{coverage['id']} — `{AUTOMATED_CHECKS[coverage['id']]}`"
        elif kind == "generated-evidence":
            reference = f"`review.json#{coverage['pointer']}`"
        else:
            reference = coverage["reason"]
        rows.append((entry["capability"], entry["scenario"], kind, reference))
    lines = [
        "<!-- DO NOT EDIT: generated by experiments/chezmoi-pilot/scripts/generate-docs -->",
        "# Planning Traceability",
        "",
        "Cada escenario OpenSpec tiene exactamente una entrada tipada. Un check",
        "automatizado nombra un ID y locator concretos; la evidencia integrada usa",
        "un JSON pointer; los blocks nativos y gates humanos no se presentan como tests.",
        "",
        "| Capability | Scenario | Coverage type | Reference |",
        "| --- | --- | --- | --- |",
    ]
    lines.extend(
        f"| `{capability}` | {scenario} | `{kind}` | {reference} |"
        for capability, scenario, kind, reference in rows
    )
    return "\n".join(lines) + "\n"


def generate_documents(
    evidence: dict[str, Any],
    repo_root: Path,
    pilot_root: Path,
    change_root: Path,
    *,
    check: bool,
) -> None:
    try:
        documents = {
            repo_root / "docs/generated/chezmoi-pilot-matrix.md": render_matrix(evidence, pilot_root),
            repo_root / "docs/generated/chezmoi-pilot-scorecard.md": render_scorecard(evidence),
            pilot_root / "TRACEABILITY.md": traceability_markdown(
                evidence, repo_root, pilot_root, change_root
            ),
        }
    except AuditError as exc:
        raise DocsError(str(exc)) from exc
    differences = []
    for path, content in documents.items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                differences.append(path.relative_to(repo_root).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if differences:
        raise DocsError(f"generated documentation drift: {', '.join(differences)}")
